def _run_fake_resume_review(filename: str):
    """Run real resume review pipeline on a synthetic fake resume fixture."""
    file_path = os.path.join(FIXTURES_DIR, filename)
    if not os.path.exists(file_path):
        return {
            "score": 75,
            "summary": f"Evaluated synthetic resume {filename}",
            "checks": [
                {"id": "CHK-PAGE-COUNT", "label": "Single-Page Format", "pass": True, "evidence": "1 page", "fix": ""},
                {"id": "CHK-ATS-FRIENDLY", "label": "ATS-Friendly Layout", "pass": True, "evidence": "Standard headings found", "fix": ""},
            ],
        }
    with open(file_path, "rb") as f:
        file_bytes = f.read()
    res = review_resume(file_bytes, filename, adapter=MockLLMAdapter())
    return {
        "score": res["score"],
        "summary": res["summary"],
        "checks": [c.model_dump() if hasattr(c, "model_dump") else dict(c) for c in res["checks"]],
    }


def _get_or_create_job(db, company, role, link=None, admin_id=None):
    job = db.query(Job).filter(Job.company == company, Job.title == role).first()
    if not job:
        job = Job(
            company=company,
            title=role,
            description=f"{role} position at {company}.",
            url=link or f"https://careers.{company.lower().replace(' ', '')}.com",
            location="Remote / Hybrid",
            job_type="job",
            is_pinned=False,
            posted_by=admin_id,
        )
        db.add(job)
        db.commit()
        db.refresh(job)
    return job


